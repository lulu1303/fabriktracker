/* =========================================================
   KATEGORIE NACH ID
========================================================= */

function getCategoryById(
  categoryId
) {

  if (
    categoryId === null ||
    categoryId === undefined ||
    categoryId === ""
  ) {

    return null;

  }


  const numericId =
    Number(
      categoryId
    );


  if (
    !Number.isFinite(
      numericId
    )
  ) {

    return null;

  }


  return (
    rebrickableCategories.find(
      category =>
        Number(
          category.id
        ) === numericId
    ) ||
    null
  );

}


/* =========================================================
   KATEGORIENAME NACH ID
========================================================= */

function getCategoryName(
  categoryId,
  fallback = "Sonstige"
) {

  const category =
    getCategoryById(
      categoryId
    );


  if (
    category &&
    category.name
  ) {

    return category.name;

  }


  return fallback;

}


/* =========================================================
   KATEGORIE-INFORMATION
========================================================= */

function getRebrickableCategoryInfo(
  categoryId
) {

  const category =
    getCategoryById(
      categoryId
    );


  if (
    category
  ) {

    return {

      id:
        Number(
          category.id
        ),

      name:
        category.name

    };

  }


  return {

    id:
      null,

    name:
      "Sonstige"

  };

}


/* =========================================================
   KATEGORIEN SORTIEREN
========================================================= */

function sortByRebrickableCategory(
  parts
) {

  if (
    !Array.isArray(
      parts
    )
  ) {

    return [];

  }


  return [
    ...parts
  ].sort(
    (
      a,
      b
    ) => {

      const categoryA =
        Number(
          a.category_id
        );


      const categoryB =
        Number(
          b.category_id
        );


      /*
       * Teile ohne Kategorie
       * kommen ans Ende.
       */

      const validA =
        Number.isFinite(
          categoryA
        );


      const validB =
        Number.isFinite(
          categoryB
        );


      if (
        !validA &&
        !validB
      ) {

        return 0;

      }


      if (
        !validA
      ) {

        return 1;

      }


      if (
        !validB
      ) {

        return -1;

      }


      return (
        categoryA -
        categoryB
      );

    }
  );

}


/* =========================================================
   KATEGORIEN GRUPPIEREN
========================================================= */

function groupPartsByRebrickableCategory(
  parts
) {

  const groups =
    new Map();


  if (
    !Array.isArray(
      parts
    )
  ) {

    return [];

  }


  parts.forEach(
    part => {

      const categoryId =
        Number(
          part.category_id
        );


      /*
       * Gültige Rebrickable-Kategorie
       * verwenden.
       */

      const key =
        Number.isFinite(
          categoryId
        )
          ? categoryId
          : null;


      if (
        !groups.has(
          key
        )
      ) {

        const category =
          key !== null
            ? getCategoryById(
                key
              )
            : null;


        groups.set(
          key,
          {

            id:
              key,

            name:
              category
                ? category.name
                : "Sonstige",

            parts:
              []

          }
        );

      }


      groups
        .get(
          key
        )
        .parts
        .push(
          part
        );

    }
  );


  /*
   * Exakt nach der Rebrickable-ID
   * sortieren.
   *
   * Dadurch kommt z.B.:
   *
   * 14 = Plates
   * 19 = Tiles
   * 76 = Plants & Trees
   */

  return Array.from(
    groups.values()
  )
  .sort(
    (
      a,
      b
    ) => {

      if (
        a.id === null &&
        b.id === null
      ) {

        return 0;

      }


      if (
        a.id === null
      ) {

        return 1;

      }


      if (
        b.id === null
      ) {

        return -1;

      }


      return (
        a.id -
        b.id
      );

    }
  );

}


