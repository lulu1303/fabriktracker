/* =========================================================
   KATEGORIE-BILD KONFIGURATION
========================================================= */

function getCategoryImageConfig(
  categoryId
) {

  const id =
    Number(
      categoryId
    );


  if (
    !Number.isFinite(id)
  ) {

    return null;

  }


  const config =
    CATEGORY_IMAGES[id];


  /*
   * Keine Konfiguration vorhanden.
   */

  if (
    !config ||
    !config.part
  ) {

    return null;

  }


  return config;

}
